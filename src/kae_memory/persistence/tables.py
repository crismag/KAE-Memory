    __table_args__ = (
        UniqueConstraint("knowledge_id", "chunk_index", "embedding_version"),
        Index("ix_knowledge_chunks_project_state", "project_id", "embedding_state"),
        Index("ix_knowledge_chunks_knowledge", "knowledge_id"),
    )

